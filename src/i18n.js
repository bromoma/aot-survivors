const I18N = { en: {}, es: {} };
for (const [ru, en, es] of I18N_ROWS) { I18N.en[ru] = en; I18N.es[ru] = es; }

function tr(s, ...a) {
  let r = s;
  if (LANG !== 'ru') {
    const d = I18N[LANG] && I18N[LANG][s];
    if (d === undefined) I18N_MISSING.add(s);
    else r = d;
  }
  if (a.length) r = r.replace(/\{(\d)\}/g, (_, i) => a[+i]);
  return r;
}

function trFields(list, fields) {
  for (const o of list) for (const f of fields) {
    const v = o[f];
    if (typeof v !== 'string') continue;
    Object.defineProperty(o, f, { get: () => tr(v), enumerable: true, configurable: true });
  }
}

function pickLang(s) {
  const q = new URLSearchParams(location.search).get('lang');
  if (q && LANGS.some(l => l[0] === q)) return q;
  const st = s && s.settings && s.settings.lang;
  if (st && LANGS.some(l => l[0] === st)) return st;
  const n = ((navigator.languages && navigator.languages[0]) || navigator.language || 'ru').slice(0, 2).toLowerCase();
  return n === 'es' ? 'es' : ['ru', 'uk', 'be', 'kk'].includes(n) ? 'ru' : 'en';
}
